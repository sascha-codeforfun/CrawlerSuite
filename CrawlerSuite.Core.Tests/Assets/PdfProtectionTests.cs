		[Fact]
		public void QualityCheck_ABlockedOrPasswordPdf_IsAGap_ARestrictedOneIsNot()
		{
			const string page = "https://site.test/ice.pdf";
			var blocked = PdfQualityAnalyzer.CheckPdfBytes(Convert.FromBase64String(Files["r3_blocked"].Base64), page);
			Assert.Equal(PdfProtectionKind.AccessibilityBlocked, blocked.Protection);
			Assert.Contains("PDF_ACCESSIBILITY_BLOCKED", blocked.GapSummary);
			Assert.Equal("accessibility blocked", blocked.ToFields()[^1]);

			var password = PdfQualityAnalyzer.CheckPdfBytes(Convert.FromBase64String(Files["r6_password"].Base64), page);
			Assert.StartsWith("PDF_PASSWORD_TO_OPEN", password.GapSummary);

			var restricted = PdfQualityAnalyzer.CheckPdfBytes(Convert.FromBase64String(Files["r6_restricted"].Base64), page);
			Assert.Equal(PdfProtectionKind.Restricted, restricted.Protection);
			Assert.DoesNotContain("PDF_ACCESSIBILITY_BLOCKED", restricted.GapSummary);
			Assert.DoesNotContain("PDF_PASSWORD_TO_OPEN", restricted.GapSummary);
			Assert.Equal("restricted", restricted.ToFields()[^1]);

			var plain = PdfQualityAnalyzer.CheckPdfBytes(Convert.FromBase64String(Plain), page);
			Assert.Equal("none", plain.ToFields()[^1]);
		}

